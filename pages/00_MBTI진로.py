import streamlit as st

# ------------------------------
# 🎯 앱 제목
# ------------------------------
st.title("🌈 MBTI로 보는 나의 진로 추천기 💼")
st.write("안녕! 👋 내 MBTI에 맞는 진로가 궁금해? 아래에서 MBTI를 골라봐~")

# ------------------------------
# 🧠 MBTI 선택
# ------------------------------
mbti_list = [
    "INTJ", "INTP", "ENTJ", "ENTP",
    "INFJ", "INFP", "ENFJ", "ENFP",
    "ISTJ", "ISFJ", "ESTJ", "ESFJ",
    "ISTP", "ISFP", "ESTP", "ESFP"
]

user_mbti = st.selectbox("👉 나의 MBTI는?", mbti_list)

# ------------------------------
# 💡 MBTI별 진로 데이터
# ------------------------------
career_dict = {
    "INTJ": ["데이터 분석가 📊", "전략 기획자 🧩"],
    "INTP": ["연구원 🔬", "개발자 💻"],
    "ENTJ": ["경영 컨설턴트 💼", "프로젝트 매니저 📅"],
    "ENTP": ["스타트업 창업가 🚀", "마케팅 기획자 📣"],
    "INFJ": ["심리상담사 💬", "작가 ✍️"],
    "INFP": ["예술가 🎨", "사회복지사 🤝"],
    "ENFJ": ["교사 🍎", "HR 매니저 💬"],
    "ENFP": ["광고 기획자 🎬", "콘텐츠 크리에이터 📱"],
    "ISTJ": ["회계사 📘", "행정직 공무원 🏛️"],
    "ISFJ": ["간호사 🏥", "초등교사 📚"],
    "ESTJ": ["기업 관리자 🧾", "프로젝트 리더 🧠"],
    "ESFJ": ["영업 관리자 🤝", "이벤트 플래너 🎉"],
    "ISTP": ["엔지니어 ⚙️", "정비사 🔧"],
    "ISFP": ["디자이너 🎨", "사진작가 📷"],
    "ESTP": ["기업가 💰", "스포츠 코치 ⚽"],
    "ESFP": ["방송인 🎤", "배우 🎭"]
}

# ------------------------------
# 🎁 결과 출력
# ------------------------------
if st.button("진로 추천 받기 ✨"):
    careers = career_dict.get(user_mbti, [])
    if careers:
        st.success(f"✅ {user_mbti} 타입인 너에게 어울리는 진로는 바로...\n\n"
                   f"1️⃣ {careers[0]}\n"
                   f"2️⃣ {careers[1]}")
        st.balloons()  # 풍선 효과 🎈
    else:
        st.warning("MBTI를 선택해줘! 😊")

# ------------------------------
# 👋 푸터
# ------------------------------
st.markdown("---")
st.caption("Made with 💖 by Streamlit & You")
